    @staticmethod
    def update_receptionist(db: Session, r_id: int, data: ReceptionistUpdate) -> Dict:
        """Update a receptionist record"""
        rec = db.query(Receptionist).filter(Receptionist.id == r_id).first()
        if not rec:
            return {"success": False, "error": "Receptionist not found"}
        
        # Update only fields provided in the schema
        update_data = data.dict(exclude_unset=True)
        for key, value in update_data.items():
            setattr(rec, key, value)
        
        db.commit()
        return {"success": True, "message": "Record updated"}

    @staticmethod
    def delete_receptionist(db: Session, r_id: int) -> Dict:
        """Soft delete (deactivate) a receptionist"""
        rec = db.query(Receptionist).filter(Receptionist.id == r_id).first()
        if rec:
            rec.status = "inactive"
            db.commit()
            return {"success": True, "message": "Receptionist deactivated"}
        return {"success": False, "error": "Not found"}

    # ----------------------
    # Search Patients
    # ----------------------
    @staticmethod
    def search_patients(db: Session, query: str) -> Dict:
        """Search database for patients by name or phone number"""
        if not query or len(query) < 3:
            return {"success": False, "error": "Search query too short"}
            
        patients = db.query(Patient).filter(
            (Patient.name.ilike(f"%{query}%")) | 
            (Patient.phone.ilike(f"%{query}%"))
        ).all()

        return {
            "success": True,
            "results": [{"id": p.id, "name": p.name, "phone": p.phone} for p in patients]
        }